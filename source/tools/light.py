"""Generate assets/css/sgai-light.css: the light (daytime) theme, derived from sgai.css.

Every rule in sgai.css that hard-codes a dark-theme colour gets a light counterpart scoped to
html[data-mode="light"] (morning and daytime). Only Simpliigence brand colours are used. Re-run after editing sgai.css.
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "css", "sgai.css")
OUT = os.path.join(ROOT, "assets", "css", "sgai-light.css")
L = 'html[data-mode="light"]'

TOKENS = """%s{
  color-scheme:light;
  --ink0:#F4F6F9;--ink1:#FFFFFF;--ink2:#F1F6FC;--ink3:#EAEFF9;--ink4:#E9EDF4;
  --text:#102548;--text2:#3A5171;--text3:#51719E;
  --sky:#2A63C4;--net:42,99,196;
  --line:rgba(31,74,144,.12);--line2:rgba(31,74,144,.2);--line3:rgba(42,99,196,.45);
  --glass:linear-gradient(170deg,#FFFFFF,#F1F6FC);
}
""" % L

# Dark navy/black neutrals used for surfaces in the dark theme.
DARK = {(4, 10, 22), (7, 18, 38), (11, 26, 52), (17, 37, 72), (23, 48, 92), (9, 20, 40), (4, 6, 11),
        (2, 3, 6), (10, 16, 28), (1, 2, 4), (3, 8, 18), (0, 0, 0)}
DARK_HEX = {"#04070d", "#010204", "#04060b", "#0b1a34", "#06122a", "#030812", "#0d2552", "#071226", "#040a16"}
SURFACE = ("background", "background-color", "background-image", "fill")
ON_BLUE = re.compile(r"background[^;]*(var\(--blue\)|var\(--deep\)|#2A63C4|#1F4A90|#3470d6)", re.I)


def rgba(m, prop):
    r, g, b, a = int(m.group(1)), int(m.group(2)), int(m.group(3)), float(m.group(4))
    if (r, g, b) in DARK or max(r, g, b) < 64:
        if "shadow" in prop:
            return "rgba(16,37,72,%.2f)" % min(a * .3, .22)
        if prop in SURFACE or prop.startswith("background"):
            return "rgba(255,255,255,%.2f)" % max(a, .72)
        return "rgba(16,37,72,%.2f)" % min(a, .6)
    if (r, g, b) == (255, 255, 255):
        if "shadow" in prop and "inset" not in prop:
            return m.group(0)
        return "rgba(16,37,72,%.3f)" % min(a * .9, .5)
    return m.group(0)


def convert(prop, val, on_blue):
    if prop.startswith("mask") or prop.startswith("-webkit-mask"):
        return val
    out = val
    if not on_blue:
        out = re.sub(r"rgba\((\d+),\s*(\d+),\s*(\d+),\s*([.\d]+)\)", lambda m: rgba(m, prop), out)
        if prop in ("color", "-webkit-text-stroke") or prop.startswith("border") or prop.startswith("outline"):
            out = re.sub(r"#fff\b|#ffffff\b", "var(--text)", out, flags=re.I)
        elif prop.startswith("background"):
            out = re.sub(r"(gradient\([^;]*?)#fff\b", r"\1var(--text)", out, flags=re.I)  # gradient text
    else:
        out = re.sub(r"rgba\((\d+),\s*(\d+),\s*(\d+),\s*([.\d]+)\)",
                     lambda m: rgba(m, prop) if "shadow" in prop and tuple(map(int, m.groups()[:3])) in DARK else m.group(0), out)
    if prop.startswith("background") or prop in ("color", "fill", "stroke") or prop.startswith("border"):
        def hexdark(m):
            h = m.group(1)
            if len(h) == 3: h = "".join(c * 2 for c in h)
            r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
            if max(r, g, b) >= 64: return m.group(0)
            return "var(--ink1)" if prop.startswith("background") else "var(--text)"
        out = re.sub(r"#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b", hexdark, out)
    return out


def scope(sel):
    parts = []
    for s in sel.split(","):
        s = s.strip()
        if s in (":root", "html"):
            parts.append(L)
        elif s.startswith("html"):
            parts.append(L + s[4:])
        else:
            parts.append(L + " " + s)
    return ",".join(parts)


def rules(css):
    """Yield (media or None, selector, body) for every style rule, skipping @keyframes and @font-face."""
    i, n = 0, len(css)
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    n = len(css)
    def block(j):
        depth = 0
        for k in range(j, n):
            if css[k] == "{": depth += 1
            elif css[k] == "}":
                depth -= 1
                if depth == 0: return k
        return n
    while i < n:
        b = css.find("{", i)
        if b < 0: break
        head = css[i:b].strip()
        e = block(b)
        inner = css[b + 1:e]
        if head.startswith("@media"):
            for _, s, body in rules(inner):
                yield head, s, body
        elif not head.startswith("@"):
            yield None, head, inner
        i = e + 1


def main():
    css = open(SRC).read()
    out = ["/* Generated by tools/light.py from sgai.css. Do not edit by hand: edit sgai.css or the overrides in light.py. */\n", TOKENS]
    for media, sel, body in rules(css):
        on_blue = bool(ON_BLUE.search(body))
        changed = []
        for decl in body.split(";"):
            if ":" not in decl: continue
            prop, val = decl.split(":", 1)
            prop = prop.strip().lower()
            if prop.startswith("--"): continue
            nv = convert(prop, val.strip(), on_blue)
            if nv != val.strip():
                changed.append(f"{prop}:{nv}")
        if changed and "background-clip:text" in body.replace(" ", "") and any(c.startswith("background:") for c in changed):
            changed += ["-webkit-background-clip:text", "background-clip:text", "color:transparent"]
        if changed:
            rule = scope(sel) + "{" + ";".join(changed) + "}"
            out.append((media + "{" + rule + "}" if media else rule) + "\n")
    out.append(EXTRA)
    open(OUT, "w").write("".join(out))
    print(OUT, len(out) - 3, "rules")


